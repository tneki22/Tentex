"""Номер страницы, оставшийся отдельным фрагментом после разбора PDF.

Разбор режет страницу на строки, и «27» внизу листа становится самостоятельным
фрагментом. Читать и связывать с темой его нечего, поэтому проход 2, чтение кусков и
привязки уроков опираются на одно определение — это.
"""

import re

#: Целый фрагмент из одной–четырёх цифр. Пять цифр и больше — уже значение, год или
#: номер документа, а не страница книги.
PAGE_NUMBER = re.compile(r"\s*\d{1,4}\s*")


def is_page_number(text: str) -> bool:
    """Фрагмент состоит только из номера страницы."""
    return PAGE_NUMBER.fullmatch(text) is not None
