def fig_probability() -> Image.Image:
    from math import comb, factorial, exp
    n, p = 12, 0.25
    ks = list(range(0, 8))
    bino = [comb(n, k) * p**k * (1 - p) ** (n - k) for k in ks]
    lam = n * p
    pois = [lam**k * exp(-lam) / factorial(k) for k in ks]
    fig, ax = plt.subplots(figsize=(3.6, 2.0))
    ax.plot(ks, bino, "o-", color="black", lw=1.0, ms=4, label="биномиальное, n=12, p=0.25")
    ax.plot(ks, pois, "s--", color="black", lw=0.8, ms=3.5, label="пуассоновское, λ=3")
    ax.set_xlabel("k", fontsize=9)
    ax.set_ylabel("P(X=k)", fontsize=9)
    ax.tick_params(labelsize=8)
    ax.legend(fontsize=7, frameon=False, loc="upper center", bbox_to_anchor=(0.5, -0.16), ncol=1)
    ax.set_ylim(0, 0.30)
    for s in ax.spines.values():
        s.set_linewidth(0.6)
    buf = io.BytesIO(); fig.savefig(buf, dpi=200, format="PNG", bbox_inches="tight"); plt.close(fig)
    buf.seek(0); return Image.open(buf).convert("RGB")


