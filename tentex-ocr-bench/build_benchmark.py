        "import heapq",
        "",
        "def dijkstra(graph, start):",
        "    dist = {v: float('inf') for v in graph}",
        "    dist[start] = 0",
        "    queue = [(0, start)]",
        "    while queue:",
        "        d, u = heapq.heappop(queue)",
        "        if d > dist[u]:",
        "            continue          # устаревшая запись в куче",
        "        for v, w in graph[u]:",
        "            if dist[u] + w < dist[v]:",
