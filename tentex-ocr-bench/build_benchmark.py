def fig_oscillation() -> Image.Image:
    t = np.linspace(0, 10, 600)
    x = np.exp(-0.25 * t) * np.cos(2.2 * t)
    env = np.exp(-0.25 * t)
    fig, ax = plt.subplots(figsize=(3.6, 2.1))
    ax.plot(t, x, color="black", lw=1.1)
    ax.plot(t, env, "--", color="black", lw=0.7)
    ax.plot(t, -env, "--", color="black", lw=0.7)
    ax.set_xlabel("t", fontsize=9)
    ax.set_ylabel("x(t)", fontsize=9)
    ax.axhline(0, color="black", lw=0.5)
    ax.set_xticks([])
    for s in ax.spines.values():
        s.set_linewidth(0.6)
    fig.tight_layout()
    buf = io.BytesIO(); fig.savefig(buf, dpi=200, format="PNG"); plt.close(fig)
    buf.seek(0); return Image.open(buf).convert("RGB")


